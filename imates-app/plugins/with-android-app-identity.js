const {
  AndroidConfig,
  withAndroidManifest,
  withAppBuildGradle,
  withDangerousMod,
} = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const START_MARKER = '// @generated by with-android-app-identity';
const NETWORK_SECURITY_CONFIG = `<?xml version="1.0" encoding="utf-8"?>
<network-security-config>
  <base-config cleartextTrafficPermitted="false" />
  <domain-config cleartextTrafficPermitted="true">
    <domain includeSubdomains="false">www.imates.com.cn</domain>
  </domain-config>
</network-security-config>
`;

module.exports = function withAndroidAppIdentity(config) {
  config = withAndroidManifest(config, (manifestConfig) => {
    const mainApplication = AndroidConfig.Manifest.getMainApplicationOrThrow(
      manifestConfig.modResults,
    );
    mainApplication.$['android:label'] = '${imatesAppName}';
    mainApplication.$['android:networkSecurityConfig'] =
      '@xml/network_security_config';
    return manifestConfig;
  });

  config = withDangerousMod(config, [
    'android',
    async (modConfig) => {
      const xmlDirectory = path.join(
        modConfig.modRequest.platformProjectRoot,
        'app',
        'src',
        'main',
        'res',
        'xml',
      );
      await fs.promises.mkdir(xmlDirectory, { recursive: true });
      await fs.promises.writeFile(
        path.join(xmlDirectory, 'network_security_config.xml'),
        NETWORK_SECURITY_CONFIG,
      );
      return modConfig;
    },
  ]);

  return withAppBuildGradle(config, (gradleConfig) => {
    if (gradleConfig.modResults.language !== 'groovy') {
      throw new Error('with-android-app-identity 目前只支持 Groovy build.gradle');
    }
    if (gradleConfig.modResults.contents.includes(START_MARKER)) {
      return gradleConfig;
    }

    const packageName = config.android?.package || 'com.cosinetech.imates.edu';
    const appName = config.name || '手机学伴';
    const identityConfig = `${START_MARKER}\n` +
      `        applicationId (findProperty("imates.applicationId") ?: "${packageName}")\n` +
      `        manifestPlaceholders.imatesAppName = findProperty("imates.appName") ?: "${appName}"`;
    const originalApplicationId = /\s*applicationId\s+['"][^'"]+['"]/;

    if (!originalApplicationId.test(gradleConfig.modResults.contents)) {
      throw new Error('无法在 android/app/build.gradle 中找到 applicationId');
    }
    gradleConfig.modResults.contents = gradleConfig.modResults.contents.replace(
      originalApplicationId,
      `\n${identityConfig}`,
    );
    return gradleConfig;
  });
};
